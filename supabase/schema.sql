-- 1. Products table (mirrors the GameCredit model in Flutter)
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  title       text           not null,
  platform    text           not null,
  price       numeric(10, 2) not null check (price >= 0),
  image       text,                       -- local asset path, nullable
  description text           not null default '',
  created_at  timestamptz    not null default now()
);

-- Price is filtered and sorted on every page load, so index it.
create index if not exists products_price_idx on public.products (price);

-- 2. Row Level Security: anyone (anon key) may READ products.
--    No insert/update/delete policies → the app cannot modify the catalog.
alter table public.products enable row level security;

drop policy if exists "Public can read products" on public.products;
create policy "Public can read products"
  on public.products
  for select
  to anon, authenticated
  using (true);

