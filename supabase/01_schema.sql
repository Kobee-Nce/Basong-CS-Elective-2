drop table if exists public.order_items cascade;
drop table if exists public.orders      cascade;
drop table if exists public.products    cascade;
drop table if exists public.categories  cascade;
drop table if exists public.profiles    cascade;
drop table if exists public.roles       cascade;

-- ------------------------------------------------------------
-- roles: 'admin' | 'customer'
-- ------------------------------------------------------------
create table public.roles (
  id          bigint generated by default as identity primary key,
  role        varchar     not null unique,
  created_at  timestamptz not null default now(),
  encoded_by  uuid references auth.users (id) on delete set null
);

-- ------------------------------------------------------------
-- profiles: one row per auth user (created by handle_new_user)
-- ------------------------------------------------------------
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  created_at  timestamptz not null default now(),
  email       text,
  firstname   text,
  role_id     bigint references public.roles (id),
  lastname    text
);

-- ------------------------------------------------------------
-- categories
-- ------------------------------------------------------------
create table public.categories (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null unique check (length(trim(name)) > 0)
);

-- ------------------------------------------------------------
-- products
-- ------------------------------------------------------------
create table public.products (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  name         text     not null check (length(trim(name)) > 0),
  description  text,
  stock        int2     not null default 0 check (stock >= 0),
  image_url    text,
  -- A category that still has products cannot be deleted.
  category_id  bigint   not null references public.categories (id) on delete restrict,
  price        float4   not null default 0 check (price >= 0)
);

create index products_price_idx    on public.products (price);
create index products_category_idx on public.products (category_id);

-- ------------------------------------------------------------
-- orders
-- ------------------------------------------------------------
create table public.orders (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  user_id     uuid not null references auth.users (id) on delete cascade,
  status      text not null default 'pending'
              check (status in ('pending', 'done', 'cancelled')),
  total       numeric(12, 2) not null default 0 check (total >= 0)
);

create index orders_user_idx on public.orders (user_id, created_at desc);

-- ------------------------------------------------------------
-- order_items
-- product_name + unit_price are a SNAPSHOT taken at checkout, so past
-- orders stay correct when a price changes or a product is deleted
-- (product_id then becomes null instead of blocking the delete).
-- ------------------------------------------------------------
create table public.order_items (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  order_id      bigint not null references public.orders (id) on delete cascade,
  product_id    bigint references public.products (id) on delete set null,
  product_name  text   not null,
  unit_price    numeric(12, 2) not null check (unit_price >= 0),
  quantity      int8   not null check (quantity > 0)
);

create index order_items_order_idx on public.order_items (order_id);

